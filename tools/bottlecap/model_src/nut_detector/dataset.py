from torch.utils.data import Dataset


def read_samples(dataset_dir: Path) -> list[dict[str, object]]:
    samples: list[dict[str, object]] = []
    with (dataset_dir / "annotations.csv").open(encoding="utf-8-sig") as file:
        for row in csv.DictReader(file):
            samples.append(
                {
                    "image": dataset_dir / "images" / row["image"],
                    "class_index": int(row["class_id"]) - 1,
                    "source_id": row.get("source_id") or Path(row["image"]).stem,
                    "is_augmented": row.get("is_augmented", "0") == "1",
                    "bbox": np.array(
                        [row["x_min"], row["y_min"], row["x_max"], row["y_max"]],
                        dtype=np.float32,
                    ),
                }
            )
    return samples


def read_fixed_split(dataset_dir: Path, split: str) -> list[dict[str, object]]:
    """Read the flat train/ or test/ split generated by the 7:1 dataset tool."""
    samples: list[dict[str, object]] = []
    annotation_path = dataset_dir / f"{split}_annotations.csv"
    with annotation_path.open(encoding="utf-8-sig") as file:
        for row in csv.DictReader(file):
            samples.append(
                {
                    "image": dataset_dir / split / row["image"],
                    "class_index": int(row["class_id"]) - 1,
                    "source_id": f"{row['source_class_folder']}/{row['source_filename']}",
                    "is_augmented": False,
                    "bbox": np.array(
                        [row["x_min"], row["y_min"], row["x_max"], row["y_max"]],
                        dtype=np.float32,
                    ),
                }
            )
    return samples


def stratified_split(
    samples: Sequence[dict[str, object]], val_fraction: float, seed: int
) -> tuple[list[int], list[int]]:
    # Split source groups, not individual augmented files. This prevents an
    # augmentation of a training photo from leaking into validation.
    source_to_indices: dict[str, list[int]] = defaultdict(list)
    source_to_class: dict[str, int] = {}
    for index, sample in enumerate(samples):
        source_id = str(sample["source_id"])
        source_to_indices[source_id].append(index)
        source_to_class[source_id] = int(sample["class_index"])
    groups: dict[int, list[str]] = defaultdict(list)
    for source_id, class_index in source_to_class.items():
        groups[class_index].append(source_id)
    rng = random.Random(seed)
    train_sources: set[str] = set()
    val_sources: set[str] = set()
    for source_ids in groups.values():
        rng.shuffle(source_ids)
        val_count = max(1, round(len(source_ids) * val_fraction))
        val_sources.update(source_ids[:val_count])
        train_sources.update(source_ids[val_count:])
    train_indices = [
        index
        for source_id in train_sources
        for index in source_to_indices[source_id]
    ]
    # Validation uses only the untouched source image for each held-out group.
    val_indices = [
        index
        for source_id in val_sources
        for index in source_to_indices[source_id]
        if not bool(samples[index]["is_augmented"])
    ]
    rng.shuffle(train_indices)
    rng.shuffle(val_indices)
    return train_indices, val_indices


def save_split(
    path: Path,
    samples: Sequence[dict[str, object]],
    train_indices: Sequence[int],
    val_indices: Sequence[int],
) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    payload = {
        "train": [Path(samples[i]["image"]).name for i in train_indices],
        "validation": [Path(samples[i]["image"]).name for i in val_indices],
    }
    path.write_text(json.dumps(payload, indent=2), encoding="utf-8")


def _flip_horizontal(image: Image.Image, box: np.ndarray) -> tuple[Image.Image, np.ndarray]:
    width = image.width
    x1, y1, x2, y2 = box
    return image.transpose(Image.Transpose.FLIP_LEFT_RIGHT), np.array(
        [width - 1 - x2, y1, width - 1 - x1, y2], dtype=np.float32
    )


def _flip_vertical(image: Image.Image, box: np.ndarray) -> tuple[Image.Image, np.ndarray]:
    height = image.height
    x1, y1, x2, y2 = box
    return image.transpose(Image.Transpose.FLIP_TOP_BOTTOM), np.array(
        [x1, height - 1 - y2, x2, height - 1 - y1], dtype=np.float32
    )


def _translate_edge(
    image: Image.Image, box: np.ndarray, dx: int, dy: int
) -> tuple[Image.Image, np.ndarray]:
    pixels = np.asarray(image)
    pad_x, pad_y = abs(dx), abs(dy)
    padded = np.pad(pixels, ((pad_y, pad_y), (pad_x, pad_x), (0, 0)), mode="edge")
    start_x = pad_x - dx
    start_y = pad_y - dy
    translated = padded[start_y : start_y + image.height, start_x : start_x + image.width]
    moved = box + np.array([dx, dy, dx, dy], dtype=np.float32)
    moved[[0, 2]] = np.clip(moved[[0, 2]], 0, image.width - 1)
    moved[[1, 3]] = np.clip(moved[[1, 3]], 0, image.height - 1)
    return Image.fromarray(translated), moved


def _rotate_edge(
    image: Image.Image, box: np.ndarray, angle: float
) -> tuple[Image.Image, np.ndarray]:
    pad = 32
    pixels = np.pad(np.asarray(image), ((pad, pad), (pad, pad), (0, 0)), mode="edge")
    padded = Image.fromarray(pixels)
    rotated = padded.rotate(angle, resample=Image.Resampling.BILINEAR)
    rotated = rotated.crop((pad, pad, pad + image.width, pad + image.height))

    cx = (image.width - 1) / 2.0
    cy = (image.height - 1) / 2.0
    radians = math.radians(angle)
    cosine, sine = math.cos(radians), math.sin(radians)
    x1, y1, x2, y2 = box
    corners = np.array([[x1, y1], [x2, y1], [x2, y2], [x1, y2]], dtype=np.float32)
    offsets = corners - np.array([cx, cy], dtype=np.float32)
    transformed = np.empty_like(offsets)
    transformed[:, 0] = cosine * offsets[:, 0] + sine * offsets[:, 1] + cx
    transformed[:, 1] = -sine * offsets[:, 0] + cosine * offsets[:, 1] + cy
    new_box = np.array(
        [
            transformed[:, 0].min(),
            transformed[:, 1].min(),
            transformed[:, 0].max(),
            transformed[:, 1].max(),
        ],
        dtype=np.float32,
    )
    new_box[[0, 2]] = np.clip(new_box[[0, 2]], 0, image.width - 1)
    new_box[[1, 3]] = np.clip(new_box[[1, 3]], 0, image.height - 1)
    return rotated, new_box


def augment(image: Image.Image, box: np.ndarray, rng: random.Random) -> tuple[Image.Image, np.ndarray]:
    if rng.random() < 0.5:
        image, box = _flip_horizontal(image, box)
    if rng.random() < 0.15:
        image, box = _flip_vertical(image, box)
    if rng.random() < 0.65:
        image, box = _translate_edge(
            image,
            box,
            rng.randint(-18, 18),
            rng.randint(-14, 14),
        )
    if rng.random() < 0.55:
        image, box = _rotate_edge(image, box, rng.uniform(-8.0, 8.0))

    image = ImageEnhance.Brightness(image).enhance(rng.uniform(0.68, 1.35))
    image = ImageEnhance.Contrast(image).enhance(rng.uniform(0.75, 1.30))
    image = ImageEnhance.Color(image).enhance(rng.uniform(0.82, 1.18))
    if rng.random() < 0.35:
        gamma = rng.uniform(0.78, 1.28)
        table = [round(255 * ((value / 255) ** gamma)) for value in range(256)]
        image = image.point(table * 3)
    if rng.random() < 0.30:
        array = np.asarray(image, dtype=np.float32)
        noise_rng = np.random.default_rng(rng.randrange(2**32))
        array += noise_rng.normal(0.0, rng.uniform(1.5, 6.0), array.shape)
        image = Image.fromarray(np.clip(array, 0, 255).astype(np.uint8))
    return image, box


def preprocess_224(image: Image.Image, box: np.ndarray) -> tuple[torch.Tensor, torch.Tensor]:
    # 320x240 -> 224x168 keeps the 4:3 geometry exactly. The remaining 56 rows
    # are filled by extending adjacent edge pixels, not black padding.
    target_size = 224
    fitted_height = 168
    resized = image.resize((target_size, fitted_height), Image.Resampling.BILINEAR)
    pixels = np.asarray(resized)
    top = (target_size - fitted_height) // 2
    bottom = target_size - fitted_height - top
    pixels = np.pad(pixels, ((top, bottom), (0, 0), (0, 0)), mode="edge").copy()

    scale_x = target_size / image.width
    scale_y = fitted_height / image.height
    transformed_box = box.copy()
    transformed_box[[0, 2]] *= scale_x
    transformed_box[[1, 3]] = transformed_box[[1, 3]] * scale_y + top
    transformed_box /= np.array([target_size - 1] * 4, dtype=np.float32)
    transformed_box = np.clip(transformed_box, 0.0, 1.0)

    tensor = torch.from_numpy(pixels).permute(2, 0, 1).float().div_(127.5).sub_(1.0)
    return tensor, torch.from_numpy(transformed_box.astype(np.float32))


class NutDataset(Dataset):
    def __init__(
        self,
        samples: Sequence[dict[str, object]],
        indices: Sequence[int],
        training: bool,
        seed: int,
    ) -> None:
        self.samples = samples
        self.indices = list(indices)
        self.training = training
        self.seed = seed
        self.epoch = 0

    def set_epoch(self, epoch: int) -> None:
        self.epoch = epoch

    def __len__(self) -> int:
        return len(self.indices)

    def __getitem__(self, item: int) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
        sample_index = self.indices[item]
        sample = self.samples[sample_index]
        with Image.open(Path(sample["image"])) as source:
            image = source.convert("RGB")
        box = np.asarray(sample["bbox"], dtype=np.float32).copy()
        if self.training:
            # Deterministic per epoch/sample, but different on every epoch.
            rng = random.Random(self.seed + self.epoch * 100_003 + sample_index * 997)
            image, box = augment(image, box, rng)
        tensor, normalized_box = preprocess_224(image, box)
        class_index = torch.tensor(int(sample["class_index"]), dtype=torch.long)
        return tensor, class_index, normalized_box
