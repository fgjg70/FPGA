# =============================================================================
# amo_diag.S — RV32A 单步诊断 (只做一件事, 把中间值如实上报)
# -----------------------------------------------------------------------------
# tohost = 0x90002000, 写入的值就是"结论":
#   1  = 全部通过
#   2  = sw 后 lw 读不回刚写的值 (基础读写就坏了)
#   3  = sw 自己写后读回不对 (写通路)
#   4  = AMO 读到 0 (地址错 或 读通路错)
#   5  = AMO rd (旧值) 不对
#   6  = AMO 写回的新值不对
#
# 【为什么单独写这一支】原来的 amo.S 一次测 9 组, 失败时只知道"第 1 组错",
# 不知道错在"地址"还是"读"还是"写"。这支程序把每一步的中间值直接写进 tohost,
# 一次仿真就能定位, 不用再靠加打印猜。
#
# AMO 用 .word 手工编码 (迷你汇编器不认 AMO 助记符):
#   amoadd.w t2, t1, (t0) = 0x0062A3AF   (rs2=t1, rs1=t0, rd=t2)
# =============================================================================

    .text
    # 数据地址: 0x90003000 (用 lui+addi 手算)
    lui  t0, 0x90003
    addi t0, t0, 0x000          # t0 = 0x90003000

    # ---- 1. 先验证基础读写: sw 100 后 lw 读回 ----
    li   t1, 100
    sw   t1, 0(t0)              # mem[0x90003000] = 100
    lw   t4, 0(t0)
    li   t3, 100
    bne  t4, t3, rep2           # 读不回 -> 2 (基础读写坏了)

    # ---- 2. AMO 读旧值 ----
    li   t1, 23
    .word 0x0062A3AF            # amoadd.w t2, t1, (t0)
    # t2 应当是旧值 100
    li   t3, 100
    bne  t2, t3, rep5           # rd 不对 -> 5

    # ---- 3. AMO 写回新值 100+23=123 ----
    lw   t4, 0(t0)
    li   t3, 123
    bne  t4, t3, rep6           # 写回不对 -> 6

    # ---- 4. AMO 读到的旧值为 0? (区分"地址错"与"读错") ----
    beq  t2, zero, rep4         # rd==0 -> 4

    # ---- 全部通过 ----
    li   a0, 0x90002000
    li   a1, 1
    sw   a1, 0(a0)
    j    done

  rep2:
    li   a0, 0x90002000
    li   a1, 2
    sw   a1, 0(a0)
    j    done
  rep4:
    li   a0, 0x90002000
    li   a1, 4
    sw   a1, 0(a0)
    j    done
  rep5:
    li   a0, 0x90002000
    li   a1, 5
    sw   a1, 0(a0)
    j    done
  rep6:
    li   a0, 0x90002000
    li   a1, 6
    sw   a1, 0(a0)
    j    done

  done:
    j    done
