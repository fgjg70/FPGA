// tb_nn_wstream.sv -- M3 unit testbench: behavioral DDR3 -> nn_wload -> fill ports
// ----------------------------------------------------------------------------
// Owner : rtl-stream (task-8 / M3).  Pass marker: "WSTREAM_TB: PASS".
//
// What is verified (directly probing the nn_mem fill write ports)
//   case_a : random 1024B at a 16B-aligned DDR address -> prefetch ->
//            every 64-bit wfill word and its bank word index checked.
//   case_b : the REAL YOLO-Fastest image (generated by
//            tools/bottlecap/gen_weights_image.py) -> all 102 streaming layers
//            (84 weight layers + 18 ADD_R Q blocks) prefetched in op order
//            with alternating banks; every weight/Q word compared against the
//            image loaded from yolo_ddr_img.hex.  Also checks the
//            sum(wlen)=319792 / sum(qlen)=44544 byte totals.
//   case_c : length/alignment boundaries
//            c1  1 B at 0x2008 (8B aligned, not 16B aligned)
//            c2  12 B (non-8B multiple) at 0x3008
//            c3  7 B at 0x4008 -> only the second 64-bit word of the beat valid
//            c4  124,416 B = the bottle-cap max layer size, source at 0x100008
//                (8B misaligned -> exercises the leading-word skip)
//            c5  len=0 (no transfer, immediate pre_done)
//            c6  Q-only transfer (wlen=0, qlen=100, non-8B multiple)
//            c7  wlen > 128 KiB -> pre_err must be raised, no fill writes
//            c8  source not 8B aligned -> pre_err, no fill writes
//   case_d : FIFO stress (BEAT_GAP=1 -> full-rate DDR) + overflow / pre_done
//            timing checks (done pulse count == 1).
//   case_e : latency sensitivity: identical 8 KiB prefetch on READ_LAT=40 and
//            READ_LAT=200 instances; both data sets must match and the busy
//            cycle delta must be ~160 cycles.
//   case_h : STREAM layout (layer_stream_offsets.json / <stem>_ddr_stream_img.hex):
//            walk all stream layers with simple running pointers
//            (w_ptr += wlen, q_ptr += qlen -- the Lead-decided sequencer scheme,
//            no ROM offset fields needed) and compare every fill word against
//            the stream image.  Also proves that the stream Q re-ordering
//            (YOLO: ADD_R Q blocks moved from the tail into op order) is
//            consistent with that accumulation scheme.
//
// Clocking note: run twice --
//   1) same clock     : vsim ... +img=... +layers=...
//   2) async ddr clock: vsim ... +img=... +layers=... +ddr_div=2
// Both runs must print "WSTREAM_TB: PASS"; the second proves the dual-clock
// FIFO/CDC path.
//
// Plusargs
//   +img=<path>           : results/bottlecap/stream/yolo_ddr_img.hex
//   +layers=<path>        : results/bottlecap/stream/yolo_layers.txt
//   +stream_img=<path>    : results/bottlecap/stream/yolo_ddr_stream_img.hex
//   +stream_layers=<path> : results/bottlecap/stream/yolo_stream_layers.txt
//   +ddr_div=<n>          : ddr_clk period = n * 10ns (default 1 == same as clk)
// ============================================================================

// ----------------------------------------------------------------------------
// fill-port monitor: captures wfill/qfill write streams per bank
// ----------------------------------------------------------------------------
module tb_wload_mon #(
  parameter int unsigned W_WORDS = 20480,
  parameter int unsigned Q_WORDS = 1024
)(
  input  logic        clk,
  input  logic        rst,
  input  logic        wfill_we,
  input  logic [17:0] wfill_addr,
  input  logic [63:0] wfill_wdata,
  input  logic        qfill_we,
  input  logic [12:0] qfill_addr,
  input  logic [63:0] qfill_wdata,
  input  logic [1:0]  cur_bank,
  input  logic        clr
);
  logic [63:0] wshadow [0:1][0:W_WORDS-1];
  logic [63:0] qshadow [0:1][0:Q_WORDS-1];
  int          wcnt, qcnt;
  int          wseq_err, qseq_err, waddr_err, qaddr_err;
  int          wnext, qnext;

  always_ff @(posedge clk) begin
    if (rst || clr) begin
      wcnt <= 0; qcnt <= 0;
      wseq_err <= 0; qseq_err <= 0;
      waddr_err <= 0; qaddr_err <= 0;
      wnext <= 0; qnext <= 0;
    end else begin
      if (wfill_we) begin
        if (int'(wfill_addr) != wnext)        wseq_err  <= wseq_err + 1;
        if (int'(wfill_addr) >= W_WORDS)      waddr_err <= waddr_err + 1;
        wshadow[cur_bank][int'(wfill_addr)] <= wfill_wdata;
        wcnt  <= wcnt + 1;
        wnext <= wnext + 1;
      end
      if (qfill_we) begin
        if (int'(qfill_addr) != qnext)        qseq_err  <= qseq_err + 1;
        if (int'(qfill_addr) >= Q_WORDS)      qaddr_err <= qaddr_err + 1;
        qshadow[cur_bank][int'(qfill_addr)] <= qfill_wdata;
        qcnt  <= qcnt + 1;
        qnext <= qnext + 1;
      end
    end
  end
endmodule


