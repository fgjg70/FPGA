      if (r == 6 && n_slayers < MAX_LAYERS) begin
        slay_opid[n_slayers] = a;
        slay_kind[n_slayers] = b;
        slay_woff[n_slayers] = c;
        slay_wlen[n_slayers] = d;
        slay_qoff[n_slayers] = e;
        slay_qlen[n_slayers] = f;
