  localparam int YOLO_Q_PAYLOAD = 44544;     // plan.q_total_payload == stream Q size
  localparam int Q_BASE_BYTE    = 327680;    // Q region base in the combined image

  logic   clk;
  logic   ddr_clk;
  logic   rst;
  integer ddr_div;

  // ---- clocks / reset ------------------------------------------------------
  initial begin : clkgen
    clk = 1'b0;
    forever #5 clk = ~clk;                       // 100 MHz
  end

  initial begin : ddrclkgen
    ddr_div = 1;
    if (!$value$plusargs("ddr_div=%d", ddr_div)) ddr_div = 1;
    if (ddr_div < 1) ddr_div = 1;
