    $fclose(fd);
    $display("[WSTREAM] stream layers parsed: %0d", n_slayers);
  endtask

  // ==========================================================================
  // case_a: single 1024B random prefetch, 16B-aligned source
  // ==========================================================================
  task automatic case_a();
    int          err0;
    int unsigned cycles;
    logic        err;
    logic [63:0] expw;
    err0 = errors;
    $display("\n[WSTREAM] ---- case_a: random 1024B prefetch (aligned) ----");
    u_ins_a.gen_data(1024, 32'hA5A5_0001);
    u_ins_a.write_bytes(32'h0000_1000, 1024);
    u_ins_a.prefetch(32'h0000_1000, 18'd1024, 32'd0, 13'd0, 1'b0, cycles, err);
    chk(!err,                        "case_a pre_err");
    chk_int(u_ins_a.u_mon.wcnt, 128, "case_a wfill word count");
    chk_int(u_ins_a.u_mon.qcnt, 0,   "case_a qfill word count");
    chk_int(u_ins_a.u_mon.wseq_err, 0, "case_a wfill addr sequence");
    chk_int(u_ins_a.u_mon.waddr_err, 0, "case_a wfill addr range");
    chk(u_ins_a.dut.u_wfifo.wr_ovf == 1'b0, "case_a W FIFO overflow");
    chk(u_ins_a.ddr_err == 1'b0,     "case_a DDR model error");
    chk_int(u_ins_a.done_pulses, 1,  "case_a pre_done pulse count");
    chk(u_ins_a.pre_busy == 1'b0,    "case_a pre_busy deasserted");
    for (int k = 0; k < 128; k++) begin
      expw = mkw(8*k, 8, 0);
      chk_word(u_ins_a.u_mon.wshadow[0][k], expw, "case_a w", k);
    end
    if (errors == err0) $display("[WSTREAM] case_a: PASS (busy=%0d cyc)", cycles);
    else                $display("[WSTREAM] case_a: FAIL (%0d new errs)", errors - err0);
    cases_run  = cases_run + 1;
    if (errors == err0) cases_pass = cases_pass + 1;
  endtask

  // ==========================================================================
  // case_b: real YOLO image, all 102 streaming layers, alternating banks
  // ==========================================================================
  task automatic case_b();
    int          err0, i, bank, k, errs_layer;
    int unsigned cycles;
    int unsigned total_w, total_q, total_cycles;
    logic        err;
    logic [63:0] expw;
    err0 = errors;
    total_w = 0;
    total_q = 0;
    total_cycles = 0;
    woff_misaligned_layers = 0;
    $display("\n[WSTREAM] ---- case_b: real YOLO image, %0d streaming layers ----",
             n_layers);
    // Load the combined DDR image (W region then Q region) at byte 0.  This is
    // done here (not in main) so case_a's scratch traffic cannot corrupt it.
    u_ins_a.load_image(g_img_path);
    for (i = 0; i < n_layers; i++) begin
      bank     = i % 2;
      errs_layer = errors;
      u_ins_a.prefetch((lay_wlen[i] > 0) ? lay_woff[i] : 32'd0,
                       18'(lay_wlen[i]),
                       (lay_qlen[i] > 0) ? (Q_BASE_BYTE + lay_qoff[i]) : 32'd0,
                       13'(lay_qlen[i]), bank[0], cycles, err);
      chk(!err, "case_b pre_err");
      chk_int(u_ins_a.u_mon.wcnt, (lay_wlen[i] + 7) / 8, "case_b wcnt");
      chk_int(u_ins_a.u_mon.qcnt, (lay_qlen[i] + 7) / 8, "case_b qcnt");
      if (u_ins_a.u_mon.wseq_err != 0 || u_ins_a.u_mon.qseq_err != 0)
        chk(1'b0, "case_b fill address sequence");
      for (k = 0; k < (lay_wlen[i] + 7) / 8; k++) begin
        expw = exp_img[lay_woff[i] / 8 + k];
        chk_word(u_ins_a.u_mon.wshadow[bank][k], expw, "case_b w", i);
      end
      for (k = 0; k < (lay_qlen[i] + 7) / 8; k++) begin
        expw = exp_img[(Q_BASE_BYTE + lay_qoff[i]) / 8 + k];
        chk_word(u_ins_a.u_mon.qshadow[bank][k], expw, "case_b q", i);
      end
      if (lay_wlen[i] > 0 && (lay_woff[i] % 16) != 0) woff_misaligned_layers++;
      total_w = total_w + lay_wlen[i];
      total_q = total_q + lay_qlen[i];
      total_cycles = total_cycles + cycles;
      if (((i + 1) % 20) == 0)
        $display("[WSTREAM] case_b: %0d/%0d layers done", i + 1, n_layers);
      if (errors - errs_layer > 0) begin
        $display("[WSTREAM] case_b: stopping at layer %0d (op_id=%0d)", i, lay_opid[i]);
        i = n_layers;
      end
    end
    chk_int(total_w, YOLO_W_PAYLOAD, "case_b sum(wlen)");
    chk_int(total_q, YOLO_Q_PAYLOAD, "case_b sum(qlen)");
    $display("[WSTREAM] case_b: totals W=%0d B Q=%0d B, 8B-misaligned W layers=%0d",
             total_w, total_q, woff_misaligned_layers);
    $display("[WSTREAM] case_b: prefetch busy cycles total=%0d over %0d layers (avg %0d), %.2f B/cycle",
             total_cycles, n_layers, total_cycles / n_layers,
             (total_w + total_q) * 1.0 / total_cycles);
    if (errors == err0) $display("[WSTREAM] case_b: PASS");
    else                $display("[WSTREAM] case_b: FAIL (%0d new errs)", errors - err0);
    cases_run  = cases_run + 1;
    if (errors == err0) cases_pass = cases_pass + 1;
  endtask

  // ==========================================================================
  // case_c: length / alignment boundaries
  // ==========================================================================
  task automatic case_c();
    int          err0;
    int unsigned cycles;
    logic        err;
    logic [63:0] expw, e0, e1;
    err0 = errors;
    $display("\n[WSTREAM] ---- case_c: length/alignment boundaries ----");

    // c1: 1 byte at an 8B-aligned but non-16B address (0x2008)
    u_ins_a.gen_data(32, 32'hC0_0001);
    u_ins_a.write_bytes(32'h0000_2000, 32);
    u_ins_a.prefetch(32'h0000_2008, 18'd1, 32'd0, 13'd0, 1'b0, cycles, err);
    expw = '0;
    expw[7:0] = u_ins_a.data_buf[8];
    chk(!err, "case_c1 pre_err");
    chk_int(u_ins_a.u_mon.wcnt, 1, "case_c1 wcnt");
    chk_word(u_ins_a.u_mon.wshadow[0][0], expw, "case_c1 w", 0);

    // c2: 12 bytes at 0x3008 (not a multiple of 8, source 8B aligned)
    u_ins_a.gen_data(32, 32'hC0_0002);
    u_ins_a.write_bytes(32'h0000_3000, 32);
    u_ins_a.prefetch(32'h0000_3008, 18'd12, 32'd0, 13'd0, 1'b1, cycles, err);
    chk(!err, "case_c2 pre_err");
    chk_int(u_ins_a.u_mon.wcnt, 2, "case_c2 wcnt");
    chk_word(u_ins_a.u_mon.wshadow[1][0], mkw(8, 8, 0),  "case_c2 w", 0);
    e1 = '0;
    for (int b = 0; b < 4; b++) e1[8*b +: 8] = u_ins_a.data_buf[16 + b];
    chk_word(u_ins_a.u_mon.wshadow[1][1], e1, "case_c2 w", 1);

    // c3: 7 bytes at 0x4008 -> single 16B beat, only the second 64b word valid
    u_ins_a.gen_data(32, 32'hC0_0003);
    u_ins_a.write_bytes(32'h0000_4000, 32);
    u_ins_a.prefetch(32'h0000_4008, 18'd7, 32'd0, 13'd0, 1'b0, cycles, err);
    chk(!err, "case_c3 pre_err");
    chk_int(u_ins_a.u_mon.wcnt, 1, "case_c3 wcnt");
    expw = '0;
    for (int b = 0; b < 7; b++) expw[8*b +: 8] = u_ins_a.data_buf[8 + b];
    chk_word(u_ins_a.u_mon.wshadow[0][0], expw, "case_c3 w", 0);

    // c4: 124,416 B (bottle-cap max layer), source at 0x100008 (8B misaligned)
    u_ins_a.gen_data(124432, 32'hC0_0004);
    u_ins_a.write_bytes(32'h0010_0000, 124432);
    u_ins_a.prefetch(32'h0010_0008, 18'd124416, 32'd0, 13'd0, 1'b1, cycles, err);
    chk(!err, "case_c4 pre_err");
    chk_int(u_ins_a.u_mon.wcnt, 15552, "case_c4 wcnt");
    for (int k = 0; k < 15552; k++) begin
      expw = mkw(8 + 8*k, 8, 0);
      chk_word(u_ins_a.u_mon.wshadow[1][k], expw, "case_c4 w", k);
    end
    $display("[WSTREAM] case_c4: 124416 B prefetch, %0d cycles", cycles);

    // c5: len = 0 (no transfer)
    u_ins_a.prefetch(32'h0000_1000, 18'd0, 32'd0, 13'd0, 1'b0, cycles, err);
    chk(!err, "case_c5 pre_err");
    chk_int(u_ins_a.u_mon.wcnt, 0, "case_c5 wcnt");
    chk_int(u_ins_a.u_mon.qcnt, 0, "case_c5 qcnt");

    // c6: Q-only transfer, qlen = 100 (not a multiple of 8)
    u_ins_a.gen_data(112, 32'hC0_0006);
    u_ins_a.write_bytes(32'h0000_2000, 112);
    u_ins_a.prefetch(32'd0, 18'd0, 32'h0000_2000, 13'd100, 1'b1, cycles, err);
    chk(!err, "case_c6 pre_err");
    chk_int(u_ins_a.u_mon.wcnt, 0,  "case_c6 wcnt");
    chk_int(u_ins_a.u_mon.qcnt, 13, "case_c6 qcnt");
    for (int k = 0; k < 12; k++)
      chk_word(u_ins_a.u_mon.qshadow[1][k], mkw(8*k, 8, 0), "case_c6 q", k);
    e1 = '0;
    for (int b = 0; b < 4; b++) e1[8*b +: 8] = u_ins_a.data_buf[96 + b];
    chk_word(u_ins_a.u_mon.qshadow[1][12], e1, "case_c6 q", 12);

    // c7: wlen > 128 KiB -> must be rejected, no fill writes
    u_ins_a.prefetch(32'h0000_1000, 18'd131080, 32'd0, 13'd0, 1'b0, cycles, err);
    chk(err == 1'b1, "case_c7 wlen>128KiB must raise pre_err");
    chk_int(u_ins_a.u_mon.wcnt, 0, "case_c7 wcnt (no transfer expected)");

    // c8: non-8B-aligned source -> must be rejected, no fill writes
    u_ins_a.prefetch(32'h0000_2001, 18'd8, 32'd0, 13'd0, 1'b0, cycles, err);
    chk(err == 1'b1, "case_c8 non-8B-aligned src must raise pre_err");
    chk_int(u_ins_a.u_mon.wcnt, 0, "case_c8 wcnt (no transfer expected)");

    if (errors == err0) $display("[WSTREAM] case_c: PASS");
    else                $display("[WSTREAM] case_c: FAIL (%0d new errs)", errors - err0);
    cases_run  = cases_run + 1;
    if (errors == err0) cases_pass = cases_pass + 1;
  endtask

  // ==========================================================================
  // case_d: FIFO stress (BEAT_GAP=1, full-rate DDR) + overflow checks
  // ==========================================================================
  task automatic case_d();
    int          err0, f0;
    int unsigned cycles;
    logic        err;
    logic [63:0] expw;
    err0 = errors;
    f0 = full_cycles_c;
    $display("\n[WSTREAM] ---- case_d: FIFO stress (BEAT_GAP=1), 16KiB ----");
    u_ins_c.gen_data(16384, 32'hD0_0001);
    u_ins_c.write_bytes(32'h0002_0000, 16384);
    u_ins_c.prefetch(32'h0002_0000, 18'd16384, 32'd0, 13'd0, 1'b1, cycles, err);
    chk(!err, "case_d pre_err");
    chk_int(u_ins_c.u_mon.wcnt, 2048, "case_d wcnt");
    chk_int(u_ins_c.u_mon.wseq_err, 0, "case_d wfill addr sequence");
    chk(u_ins_c.dut.u_wfifo.wr_ovf == 1'b0, "case_d W FIFO overflow sticky");
    chk_int(u_ins_c.done_pulses, 1, "case_d pre_done pulse count");
    chk(u_ins_c.pre_busy == 1'b0, "case_d pre_busy deasserted");
    for (int k = 0; k < 2048; k++) begin
      expw = mkw(8*k, 8, 2);
      chk_word(u_ins_c.u_mon.wshadow[1][k], expw, "case_d w", k);
