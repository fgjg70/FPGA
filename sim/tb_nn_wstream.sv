    $display("[WSTREAM] case_d: 16KiB at BEAT_GAP=1, busy=%0d cyc, FIFO full cycles=%0d",
             cycles, full_cycles_c - f0);
    if (errors == err0) $display("[WSTREAM] case_d: PASS");
    else                $display("[WSTREAM] case_d: FAIL (%0d new errs)", errors - err0);
    cases_run  = cases_run + 1;
    if (errors == err0) cases_pass = cases_pass + 1;
  endtask

  // ==========================================================================
  // case_e: read-latency sensitivity (READ_LAT 40 vs 200)
  // ==========================================================================
  task automatic case_e();
    int          err0, delta;
    int unsigned cyc_a, cyc_b;
    logic        err_a, err_b;
    logic [63:0] expw;
    err0 = errors;
    $display("\n[WSTREAM] ---- case_e: latency sensitivity (READ_LAT 40 vs 200) ----");
    u_ins_a.gen_data(8192, 32'hE0_0001);
    u_ins_a.write_bytes(32'h0008_0000, 8192);
    u_ins_b.gen_data(8192, 32'hE0_0001);
    u_ins_b.write_bytes(32'h0008_0000, 8192);
    u_ins_a.prefetch(32'h0008_0000, 18'd8192, 32'd0, 13'd0, 1'b0, cyc_a, err_a);
    u_ins_b.prefetch(32'h0008_0000, 18'd8192, 32'd0, 13'd0, 1'b1, cyc_b, err_b);
    chk(!err_a, "case_e A pre_err");
    chk(!err_b, "case_e B pre_err");
    chk_int(u_ins_a.u_mon.wcnt, 1024, "case_e A wcnt");
    chk_int(u_ins_b.u_mon.wcnt, 1024, "case_e B wcnt");
    for (int k = 0; k < 1024; k++) begin
      expw = mkw(8*k, 8, 0);
      chk_word(u_ins_a.u_mon.wshadow[0][k], expw, "case_e A w", k);
      chk_word(u_ins_b.u_mon.wshadow[1][k], expw, "case_e B w", k);
    end
    delta = int'(cyc_b) - int'(cyc_a);
    $display("[WSTREAM] case_e: busy cycles A(READ_LAT=40)=%0d B(READ_LAT=200)=%0d delta=%0d (expect ~%0d)",
             cyc_a, cyc_b, delta, 160 * ddr_div);
    chk(delta > 160 * ddr_div - 48 && delta < 160 * ddr_div + 48,
        "case_e latency delta ~160 ddr cycles");
    if (errors == err0) $display("[WSTREAM] case_e: PASS");
    else                $display("[WSTREAM] case_e: FAIL (%0d new errs)", errors - err0);
    cases_run  = cases_run + 1;
    if (errors == err0) cases_pass = cases_pass + 1;
  endtask

  // ==========================================================================
  // case_h: stream layout + running-pointer accumulation (Lead decision)
  //   Load the stream image (W payloads then Q payloads, both in op order, no
  //   padding).  Walk all stream layers exactly like a sequencer would:
  //       w_ptr starts 0, q_ptr starts 0
  //       prefetch(src = W_STREAM_BASE + w_ptr, wlen,
  //                qsrc = Q_STREAM_BASE + q_ptr, qlen)
  //       w_ptr += wlen; q_ptr += qlen
  //   No ROM offset fields are involved -- this is the "no extra ROM fields"
  //   scheme.  Every fill word is compared against the stream image and the
  //   accumulated pointers must equal the generator's per-op stream offsets.
  // ==========================================================================
  task automatic case_h();
    int          err0, i, k, errs_layer;
    int unsigned cycles;
    int unsigned wptr, qptr, qbase;
    int unsigned total_cycles;
    logic        err;
    logic [63:0] expw;
    err0 = errors;
    wptr = 0;
    qptr = 0;
    total_cycles = 0;
    $display("\n[WSTREAM] ---- case_h: stream layout, running-pointer accumulation ----");
    if (n_slayers == 0) begin
      chk(1'b0, "case_h: no stream layers parsed");
    end else begin
      // stream image: W payloads first (YOLO_W_PAYLOAD bytes), then Q payloads
      qbase = YOLO_W_PAYLOAD;
      u_ins_b.load_image(g_stream_img_path);
      for (i = 0; i < n_slayers; i++) begin
        errs_layer = errors;
        // sanity: the generator's stream offset table must equal our running sum
        if ((slay_wlen[i] > 0) && (slay_woff[i] != int'(wptr)))
          chk(1'b0, "case_h: W stream offset != running w_ptr");
        if ((slay_qlen[i] > 0) && (slay_qoff[i] != int'(qptr)))
          chk(1'b0, "case_h: Q stream offset != running q_ptr");
        u_ins_b.prefetch(wptr, 18'(slay_wlen[i]),
                         (slay_qlen[i] > 0) ? (qbase + qptr) : 32'd0,
                         13'(slay_qlen[i]), i[0], cycles, err);
        chk(!err, "case_h pre_err");
        chk_int(u_ins_b.u_mon.wcnt, (slay_wlen[i] + 7) / 8, "case_h wcnt");
        chk_int(u_ins_b.u_mon.qcnt, (slay_qlen[i] + 7) / 8, "case_h qcnt");
        if (u_ins_b.u_mon.wseq_err != 0 || u_ins_b.u_mon.qseq_err != 0)
          chk(1'b0, "case_h fill address sequence");
        for (k = 0; k < (slay_wlen[i] + 7) / 8; k++) begin
          expw = exp_stream_img[wptr / 8 + k];
          chk_word(u_ins_b.u_mon.wshadow[i[0]][k], expw, "case_h w", i);
        end
        for (k = 0; k < (slay_qlen[i] + 7) / 8; k++) begin
          expw = exp_stream_img[(qbase + qptr) / 8 + k];
          chk_word(u_ins_b.u_mon.qshadow[i[0]][k], expw, "case_h q", i);
        end
        wptr = wptr + slay_wlen[i];
        qptr = qptr + slay_qlen[i];
        total_cycles = total_cycles + cycles;
        if (errors - errs_layer > 0) begin
          $display("[WSTREAM] case_h: stopping at stream layer %0d (op_id=%0d)",
                   i, slay_opid[i]);
          i = n_slayers;
        end
      end
      chk_int(int'(wptr), YOLO_W_PAYLOAD, "case_h final w_ptr");
      chk_int(int'(qptr), YOLO_Q_PAYLOAD, "case_h final q_ptr");
      $display("[WSTREAM] case_h: %0d layers, pointers W=%0d/Q=%0d, total busy=%0d cyc, %.2f B/cycle",
               n_slayers, wptr, qptr, total_cycles,
               (wptr + qptr) * 1.0 / total_cycles);
    end
    if (errors == err0) $display("[WSTREAM] case_h: PASS");
    else                $display("[WSTREAM] case_h: FAIL (%0d new errs)", errors - err0);
    cases_run  = cases_run + 1;
    if (errors == err0) cases_pass = cases_pass + 1;
  endtask

  // ==========================================================================
  // case_g (only with +define+HAVE_NNMEM): real nn_mem wfill/qfill integration
  //   prefetch one layer into the inactive bank of a real nn_mem, then read the
  //   layer back through nn_mem's public W/Q read ports and compare with the
  //   image.  Also checks that the *active* bank was not disturbed.
  // ==========================================================================
`ifdef HAVE_NNMEM
  task automatic case_g();
    int          err0, i, k, lidx;
    int unsigned cycles;
    int unsigned nwords, nwin, qwords;
    logic        err;
    logic [127:0] win;
    logic [63:0]  qw;
    err0 = errors;
    lidx = -1;
    $display("\n[WSTREAM] ---- case_g: real nn_mem wfill/qfill integration ----");
    u_ins_n.load_image(g_img_path);
    for (i = 0; i < n_layers; i++) begin
      if ((lidx < 0) && (lay_wlen[i] >= 4096) && (lay_wlen[i] <= 8192) &&
          (lay_qlen[i] > 0))
        lidx = i;
    end
    if (lidx < 0) begin
      chk(1'b0, "case_g: no suitable layer found (4096..8192 B with Q)");
    end else begin
      $display("[WSTREAM] case_g: layer idx=%0d op_id=%0d woff=%0d wlen=%0d qoff=%0d qlen=%0d",
               lidx, lay_opid[lidx], lay_woff[lidx], lay_wlen[lidx],
               lay_qoff[lidx], lay_qlen[lidx]);
      // destination bank = 1 -> nn_mem fills ~w_bank_sel = 1 (w_bank_sel=0)
      u_ins_n.prefetch(lay_woff[lidx], 18'(lay_wlen[lidx]),
                       Q_BASE_BYTE + lay_qoff[lidx], 13'(lay_qlen[lidx]),
                       1'b1, cycles, err);
      chk(!err, "case_g pre_err");
      // ---- read back W through nn_mem's engine read port ------------------
      nwords = lay_wlen[lidx] / 8;
      nwin   = (nwords + 1) / 2;
      for (k = 0; k < nwin; k++) begin
        u_ins_n.read_w_window(1'b1, k, win);
        chk_word(win[63:0], exp_img[lay_woff[lidx]/8 + 2*k], "case_g w", 2*k);
        if ((2*k + 1) < (int'(nwords)))
          chk_word(win[127:64], exp_img[lay_woff[lidx]/8 + 2*k + 1], "case_g w", 2*k+1);
      end
      // ---- read back Q through nn_mem's Q read port -----------------------
      qwords = (lay_qlen[lidx] + 7) / 8;
      for (k = 0; k < (int'(qwords)); k++) begin
        u_ins_n.read_q_word(1'b1, k, qw);
        chk_word(qw, exp_img[(Q_BASE_BYTE + lay_qoff[lidx])/8 + k], "case_g q", k);
      end
      // ---- active bank (bank0) must be untouched (zero after sim init) ----
      u_ins_n.read_w_window(1'b0, 0, win);
      chk(win == 128'd0, "case_g active bank0 untouched (word 0)");
      u_ins_n.read_w_window(1'b0, (nwin > 4) ? 4 : 0, win);
      chk(win == 128'd0, "case_g active bank0 untouched (window 4)");
      $display("[WSTREAM] case_g: read back %0d W words / %0d Q words, prefetch busy=%0d cyc",
               nwords, qwords, cycles);
    end
    if (errors == err0) $display("[WSTREAM] case_g: PASS");
    else                $display("[WSTREAM] case_g: FAIL (%0d new errs)", errors - err0);
    cases_run  = cases_run + 1;
    if (errors == err0) cases_pass = cases_pass + 1;
  endtask
`endif

  // ==========================================================================
  // main
  // ==========================================================================
  initial begin : main
    string img_path, layers_path, stream_img_path, stream_layers_path;
    wait (!rst);
    repeat (10) @(posedge clk);
    errors     = 0;
    err_shown  = 0;
    cases_run  = 0;
    cases_pass = 0;
    n_layers   = 0;
    n_slayers  = 0;
    img_path   = "";
    layers_path = "";
    stream_img_path = "";
    stream_layers_path = "";
    g_stream_img_path = "";
    $display("================================================================");
    $display("[WSTREAM] tb_nn_wstream start: clk=100MHz ddr_div=%0d", ddr_div);
    $display("================================================================");

    if (!$value$plusargs("img=%s", img_path)) begin
      errors = errors + 1;
      $display("[WSTREAM][FAIL] missing +img=<yolo_ddr_img.hex>");
    end
    if (!$value$plusargs("layers=%s", layers_path)) begin
      errors = errors + 1;
      $display("[WSTREAM][FAIL] missing +layers=<yolo_layers.txt>");
    end
    if (!$value$plusargs("stream_img=%s", stream_img_path)) begin
      errors = errors + 1;
      $display("[WSTREAM][FAIL] missing +stream_img=<yolo_ddr_stream_img.hex>");
    end
    if (!$value$plusargs("stream_layers=%s", stream_layers_path)) begin
      errors = errors + 1;
      $display("[WSTREAM][FAIL] missing +stream_layers=<yolo_stream_layers.txt>");
    end
    if (errors == 0) begin
      $display("[WSTREAM] image        : %s", img_path);
      $display("[WSTREAM] layers       : %s", layers_path);
      $display("[WSTREAM] stream image : %s", stream_img_path);
      $display("[WSTREAM] stream layers: %s", stream_layers_path);
      $readmemh(img_path, exp_img);
      $readmemh(stream_img_path, exp_stream_img);
      load_layers(layers_path);
      load_stream_layers(stream_layers_path);
      g_img_path = img_path;
      g_stream_img_path = stream_img_path;
      if (n_layers == 0 || n_slayers == 0) begin
        errors = errors + 1;
        $display("[WSTREAM][FAIL] no layers parsed (plan=%0d stream=%0d)",
                 n_layers, n_slayers);
      end
      if (errors == 0) begin
        case_a();
        case_b();
        case_c();
        case_d();
        case_e();
        case_h();
`ifdef HAVE_NNMEM
        case_g();
`endif
      end
    end

    $display("\n================================================================");
    $display("[WSTREAM] SUMMARY: %0d/%0d cases pass, errors=%0d (ddr_div=%0d)",
             cases_pass, cases_run, errors, ddr_div);
    $display("================================================================");
    if (errors == 0) $display("WSTREAM_TB: PASS");
    else             $display("WSTREAM_TB: FAIL (%0d errors)", errors);
    $finish;
  end

