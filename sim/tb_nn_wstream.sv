  initial begin
    for (int i = 0; i < BUF_BYTES; i++) data_buf[i] = 8'h00;
  end

  always_ff @(posedge clk) begin
    if (rst || clr) done_pulses <= 0;
    else if (pre_done) done_pulses <= done_pulses + 1;
  end

  // ---- tasks called from the top TB ----------------------------------------
  task automatic load_image(input string path);
    u_ddr.load_hex(path, 0);
  endtask

  task automatic gen_data(input int unsigned nbytes, input int unsigned seed0);
    int unsigned s;
    s = seed0;
    for (int i = 0; i < nbytes; i++) begin
      s = s * 32'd1664525 + 32'd1013904223;
      data_buf[i] = s[7:0];
    end
  endtask

  function automatic logic [63:0] dword(input int unsigned off);
    for (int b = 0; b < 8; b++)
      dword[8*b +: 8] = data_buf[off + b];
  endfunction

  // write nbytes from data_buf[0..] into DDR at a 16B-aligned address.
  // The DDR write port lives in the ddr_clk domain, so the whole transaction
  // is driven off ddr_clk (works for both ddr_clk==clk and ddr_clk=clk/2).
  task automatic write_bytes(input int unsigned ddr_byte_addr,
                             input int unsigned nbytes);
    int unsigned beats;
    beats = (nbytes + 15) / 16;
    while (ddr_busy) @(posedge ddr_clk);
    @(negedge ddr_clk);
    ddr_wr_re   = 1'b1;
    ddr_wr_addr = ddr_byte_addr;
    ddr_wr_len  = beats[15:0];
    @(posedge ddr_clk);
    @(negedge ddr_clk);
    ddr_wr_re = 1'b0;
    for (int b = 0; b < beats; b++) begin
      ddr_wr_valid = 1'b1;
      ddr_wr_data  = {dword(16*b + 8), dword(16*b)};
      @(posedge ddr_clk);
      @(negedge ddr_clk);
    end
    ddr_wr_valid = 1'b0;
    while (ddr_busy) @(posedge ddr_clk);
  endtask

  // one prefetch job; returns busy cycles and the pre_err flag
  task automatic prefetch(input logic [31:0]  wsrc,
                          input logic [17:0]  wlen,
                          input logic [31:0]  qsrc,
                          input logic [12:0]  qlen,
                          input logic         bank,
                          output int unsigned cycles,
                          output logic        err);
    @(negedge clk);
    cur_bank      = {1'b0, bank};
    clr           = 1'b1;
    pre_start     = 1'b1;
    pre_src_addr  = wsrc;
    pre_wlen      = wlen;
    pre_qsrc_addr = qsrc;
    pre_qlen      = qlen;
    pre_bank      = bank;
    @(posedge clk);
    @(negedge clk);
    pre_start = 1'b0;
    clr       = 1'b0;
    cycles    = 0;
    while (!pre_done && cycles < 32'd2000000) begin
      @(posedge clk);
      cycles = cycles + 1;
    end
    if (pre_done) err = pre_err;
    else          err = 1'b1;
    // let TB-side monitor counters (NBA-updated at the same edge) settle
    repeat (2) @(posedge clk);
  endtask
endmodule


