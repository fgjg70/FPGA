  int          lay_kind  [0:MAX_LAYERS-1];
  int          lay_woff  [0:MAX_LAYERS-1];
  int          lay_wlen  [0:MAX_LAYERS-1];
  int          lay_qoff  [0:MAX_LAYERS-1];
  int          lay_qlen  [0:MAX_LAYERS-1];
  int          n_layers;
  int          slay_opid  [0:MAX_LAYERS-1];
  int          slay_kind  [0:MAX_LAYERS-1];
  int          slay_woff  [0:MAX_LAYERS-1];
  int          slay_wlen  [0:MAX_LAYERS-1];
  int          slay_qoff  [0:MAX_LAYERS-1];
  int          slay_qlen  [0:MAX_LAYERS-1];
  int          n_slayers;

  int          errors;
  int          err_shown;
  int          cases_run;
  int          cases_pass;
  int          full_cycles_c;
  int          woff_misaligned_layers;
  string       g_img_path;
  string       g_stream_img_path;

  // FIFO "full" cycle counter on the BEAT_GAP=1 instance (case_d evidence)
  always_ff @(posedge clk) begin
    if (rst) full_cycles_c <= 0;
    else if (u_ins_c.dut.u_wfifo.wfull) full_cycles_c <= full_cycles_c + 1;
  end

  // ---- check helpers ------------------------------------------------------
  task automatic chk(input logic cond, input string ctx);
    if (!cond) begin
      errors = errors + 1;
      if (err_shown < 25) begin
        err_shown = err_shown + 1;
        $display("[WSTREAM][FAIL] %s", ctx);
      end
    end
  endtask

  task automatic chk_word(input logic [63:0] got, input logic [63:0] exp,
                          input string ctx, input int unsigned idx);
    if (got !== exp) begin
      errors = errors + 1;
      if (err_shown < 25) begin
        err_shown = err_shown + 1;
        $display("[WSTREAM][FAIL] %s[%0d] got=%016x exp=%016x",
                 ctx, idx, got, exp);
      end
    end
  endtask

  task automatic chk_int(input int got, input int exp, input string ctx);
    if (got !== exp) begin
      errors = errors + 1;
      if (err_shown < 25) begin
        err_shown = err_shown + 1;
        $display("[WSTREAM][FAIL] %s got=%0d exp=%0d", ctx, got, exp);
      end
    end
  endtask

  function automatic logic [63:0] mkw(input int unsigned off,
                                      input int unsigned nbytes,
                                      input int unsigned inst);
    logic [63:0] w;
    w = '0;
    for (int b = 0; b < 8; b++) begin
      if (b < nbytes) begin
        case (inst)
          0: w[8*b +: 8] = u_ins_a.data_buf[off + b];
          1: w[8*b +: 8] = u_ins_b.data_buf[off + b];
          2: w[8*b +: 8] = u_ins_c.data_buf[off + b];
          default: w[8*b +: 8] = 8'h00;
        endcase
      end
    end
    mkw = w;
  endfunction

  // ---- layer table parser -------------------------------------------------
  task automatic load_layers(input string path);
    integer fd, r, a, b, c, d, e, f;
    reg [8*128-1:0] line;
    fd = $fopen(path, "r");
    if (fd == 0) begin
      errors = errors + 1;
      $display("[WSTREAM][FAIL] cannot open layers file: %s", path);
      return;
    end
    n_layers = 0;
    while (!$feof(fd)) begin
      r = $fgets(line, fd);
      if (r == 0) break;
      r = $sscanf(line, "%d %d %d %d %d %d", a, b, c, d, e, f);
      if (r == 6 && n_layers < MAX_LAYERS) begin
        lay_opid[n_layers] = a;
        lay_kind[n_layers] = b;
        lay_woff[n_layers] = c;
        lay_wlen[n_layers] = d;
        lay_qoff[n_layers] = e;
        lay_qlen[n_layers] = f;
        n_layers = n_layers + 1;
      end
    end
    $fclose(fd);
    $display("[WSTREAM] layers parsed: %0d", n_layers);
  endtask

  // ---- stream-layout layer table parser (same 6 columns, stream offsets) ---
  task automatic load_stream_layers(input string path);
    integer fd, r, a, b, c, d, e, f;
    reg [8*128-1:0] line;
    fd = $fopen(path, "r");
    if (fd == 0) begin
      errors = errors + 1;
      $display("[WSTREAM][FAIL] cannot open stream layers file: %s", path);
      return;
    end
    n_slayers = 0;
    while (!$feof(fd)) begin
      r = $fgets(line, fd);
      if (r == 0) break;
